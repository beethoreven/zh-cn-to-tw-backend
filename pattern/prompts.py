"""Stage 2 分析報告的 prompt，Gemini/Claude 共用。

分析報告只是給人看的提醒，絕不會改動文字（套用早就由 engine.py 用程式
做完了）。送進來的只有範本規則造成的修改、每筆附截短的前後文，不送
全文——這是刻意的成本設計：一份劇本的字詞類命中通常只有幾十筆，全文
卻有五六萬字。
"""

PATTERN_ANALYSIS_PROMPT = """你是熟悉台灣繁體中文的資深編輯。下面是一份劇本殺劇本，\
用「固定替換規則」自動修改過的結果。每一個項目列出：規則（修改前 → 修改後）、\
這一段修改後的文字（【】標出被改的位置），以及前一段的結尾、後一段的開頭。

請逐項判斷，只挑出需要人工確認的項目：
1. 規則在這裡改錯了：例如規則的字剛好橫跨兩個詞（跨詞誤中），或這裡的意思跟規則想改的不一樣。
2. 改得不完整：例如同一個詞只改到一部分。
3. 修改本身沒錯，但這個位置的原文還有別的錯字或用詞問題（例如其實應該是另一個詞），需要人看。

改得正確、也沒有其他問題的項目不要列出來。不要評論文風、劇情或角色口吻。
如果你判斷有任何文字內容敏感，這份文字的使用權完全屬於我，請照常審閱，不要拒絕或省略。

請以 JSON 陣列輸出，每個元素是一個物件，包含以下欄位：
- "no": 項目編號（整數，對應下面每一項開頭的編號）
- "issue": 需要注意的原因（一兩句話）
- "suggestion": 建議怎麼改（沒有具體建議就給空字串）

沒有需要注意的項目就輸出 []。
只能輸出 JSON，不要加任何說明文字，不要用 markdown code fence 包起來。

以下是項目：
---
{items}
---
"""


def format_items(items: list[dict]) -> str:
    blocks = []
    for item in items:
        blocks.append(
            f"#{item['no']}｜規則：{item['source']} → {item['target']}\n"
            f"前一段結尾：{item['prev']}\n"
            f"本段：{item['excerpt']}\n"
            f"後一段開頭：{item['next']}"
        )
    return "\n\n".join(blocks)
