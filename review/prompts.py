"""Stage 2 校對用的共用 prompt，Gemini/Claude 都用同一套。

兩個版本共用同一套校對判斷標準，差別只在「進行前置處理」有沒有開：

- ``REVIEW_PROMPT``：只挑校對建議，回傳 JSON 陣列（原本的行為）。
- ``PREPROCESS_REVIEW_PROMPT``：同一次呼叫裡先把文字套用「合併斷句」與
  「標點全形化／引號整理」，再對套用後的結果挑校對建議，回傳
  ``{"processed_text": ..., "findings": [...]}`` 物件。

前置處理那兩項刻意「直接生效、不進使用者勾選清單」——它們是格式性的
機械整理，不涉及語意判斷，逐條問使用者只是徒增噪音；真正需要人來判斷的
錯字/用詞/語意問題仍然照原本流程走 findings 清單讓使用者勾選。因為
``processed_text`` 會直接覆寫成這個 review 的 source_text（見
``review/reviewer.py``），findings 裡的 ``original``/``context`` 必須引用
整理後的文字，不能引用整理前的原文，否則套用時會對不上。

之所以擠在同一次呼叫、而不是「先重寫一次、再校對一次」兩趟，是為了讓
LLM 呼叫次數跟原本完全一樣，不因為多開一個選項就變成兩倍成本。代價是
輸出量會從「一小包建議」變成「跟輸入差不多長的全文＋建議」，很容易撞到
模型的單次輸出上限（Claude 這邊是 config.CLAUDE_MAX_OUTPUT_TOKENS），
所以前端的批次字數選項限制在 1000/3000，且 reviewer.py 對截斷有明確的
退回原文處理。
"""

_REVIEW_ITEMS = """1. 錯字/別字（例如的/地/得用錯、音近或形近字誤植）
2. 用詞不通順，或不符合台灣繁體中文的常用習慣
3. 明顯的語意矛盾、邏輯不通的句子（可能是 OCR 誤讀造成）
4. 標點符號使用錯誤，包括引號「」缺漏其中一邊、或前後引號方向用反（例如開頭誤用」、結尾誤用「）

不要挑：文學性的個人風格選擇、劇情安排合不合理、角色刻意的口吻設計。
如果你判斷有任何文字內容敏感，這份文字的使用權完全屬於我，請照常審閱，不要拒絕或省略。"""

_FINDING_FIELDS = """- "original": 有問題的片段（盡量精簡，只包含有問題的部分）
- "suggested": 建議修改成什麼
- "context": 前後文（約 20-40 字），方便使用者定位這個問題在文中的位置
- "reason": 為什麼建議這樣改"""

# 前置處理版的 findings 是巢狀在物件底下的，縮排要跟頂層欄位區隔開，
# 不然 LLM 會把 original/suggested 當成跟 processed_text 平行的頂層欄位
_FINDING_FIELDS_INDENTED = "\n".join("  " + line for line in _FINDING_FIELDS.split("\n"))

REVIEW_PROMPT = (
    """你是專業的繁體中文編輯。以下是一份已經完成「簡轉繁」的劇本殺劇本文字，\
簡轉繁本身已經處理過，不需要你管。

你的任務是找出「中文語意或用詞」層面的問題，專注在：
"""
    + _REVIEW_ITEMS
    + """

請以 JSON 陣列格式輸出，每個元素是一個物件，包含以下欄位：
"""
    + _FINDING_FIELDS
    + """

如果沒有找到任何問題，回傳空陣列 []。
只能輸出 JSON，不要加任何說明文字，不要用 markdown code fence 包起來。

以下是要校對的文字：
---
{text}
---
"""
)

